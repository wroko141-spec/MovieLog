class Command(BaseCommand):
    help = 'Добавляет в каталог демонстрационные фильмы и жанры'

    def handle(self, *args, **options):
        added = 0
        for title, year, genres, desc in MOVIES:
            movie, created = Movie.objects.get_or_create(title=title, year=year, defaults={'description': desc})
            if created:
                added += 1
            movie.genres.add(*[Genre.objects.get_or_create(name=g)[0] for g in genres])
            if not movie.description:
                movie.description = desc
                movie.save(update_fields=['description'])
        self.stdout.write(self.style.SUCCESS(f'Готово: добавлено фильмов - {added}, всего - {Movie.objects.count()}'))
